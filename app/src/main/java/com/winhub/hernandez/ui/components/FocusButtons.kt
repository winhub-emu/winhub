import com.winhub.hernandez.ui.screens.deckDragSelf

/*
 * Drop-ins for the four Material buttons (signatures and defaults copied from material3 1.2.0):
 * each joins the surrounding DeckDragFrame so the smooth drag ring glides onto it. Outside a frame
 * (or in a Dialog window) deckDragSelf is a no-op and the global focus outline still applies.
 */

@Composable
fun Button(
    onClick: () -> Unit,
    modifier: Modifier = Modifier,
    enabled: Boolean = true,
    shape: Shape = ButtonDefaults.shape,
    colors: ButtonColors = ButtonDefaults.buttonColors(),
    elevation: ButtonElevation? = ButtonDefaults.buttonElevation(),
    border: BorderStroke? = null,
    contentPadding: PaddingValues = ButtonDefaults.ContentPadding,
    interactionSource: MutableInteractionSource = remember { MutableInteractionSource() },
    content: @Composable RowScope.() -> Unit,
) {
    androidx.compose.material3.Button(
        onClick = onClick,
        modifier = if (enabled) modifier.deckDragSelf() else modifier,
        enabled = enabled,
        shape = shape,
        colors = colors,
        elevation = elevation,
        border = border,
        contentPadding = contentPadding,
        interactionSource = interactionSource,
        content = content,
    )
}

